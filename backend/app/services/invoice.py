"""Printable PDF invoices for completed sales.

Customer-facing: shows what was sold, to whom, by whom and for how much. Never the dealer's
cost or profit, and no tax or registration figures, since the system records none.
"""

import unicodedata
from collections.abc import Iterator
from decimal import Decimal
from zoneinfo import ZoneInfo

from fpdf import FPDF

from app.models import Purchase, SaleChannel

NOT_INCLUDED = "Taxes, fees and registration are not included in this invoice."


def invoice_number(sale_id: int) -> str:
    return f"INV-{sale_id:06d}"


def _money(value: Decimal) -> str:
    return f"${value:,.2f}"


def _customer(sale: Purchase) -> list[str]:
    if sale.channel is SaleChannel.ONLINE and sale.buyer is not None:
        return [sale.buyer.full_name, sale.buyer.email]
    return [part for part in (sale.customer_name, sale.customer_email, sale.customer_phone) if part]


def invoice_lines(
    sale: Purchase, *, dealer_name: str, dealer_email: str | None, tz: str = "UTC"
) -> Iterator[str]:
    """The invoice's text, in reading order (also what the tests check)."""
    sold = sale.sold_at.astimezone(ZoneInfo(tz))
    yield f"Invoice {invoice_number(sale.id)}"
    yield f"Sale reference #{sale.id}"
    yield f"Date of sale: {sold.day} {sold:%b %Y}"
    yield "Sold by"
    yield dealer_name
    if dealer_email:
        yield dealer_email
    yield "Bill to"
    yield from _customer(sale)
    yield "Vehicle"
    yield sale.vehicle_label
    yield f"Quantity: {sale.quantity}"
    yield f"Price per unit: {_money(sale.unit_price)}"
    yield f"Total: {_money(sale.total_price)}"
    yield NOT_INCLUDED


def _latin1(text: str) -> str:
    """The built-in PDF fonts cover Latin-1 only: drop accents where possible, else '?'."""
    plain = unicodedata.normalize("NFKD", text)
    plain = "".join(c for c in plain if not unicodedata.combining(c))
    return plain.encode("latin-1", "replace").decode("latin-1")


class _Invoice(FPDF):
    def label(self, text: str) -> None:
        self.set_font("Helvetica", "B", 8)
        self.set_text_color(110, 110, 110)
        self.cell(0, 5, _latin1(text.upper()), new_x="LMARGIN", new_y="NEXT")

    def line_text(self, text: str, size: int = 10, bold: bool = False) -> None:
        self.set_font("Helvetica", "B" if bold else "", size)
        self.set_text_color(20, 20, 20)
        self.multi_cell(0, 5.5, _latin1(text), new_x="LMARGIN", new_y="NEXT")


def render_invoice(
    sale: Purchase, *, dealer_name: str, dealer_email: str | None, tz: str = "UTC"
) -> bytes:
    sold = sale.sold_at.astimezone(ZoneInfo(tz))
    pdf = _Invoice(format="A4")
    pdf.set_title(invoice_number(sale.id))
    pdf.set_author(_latin1(dealer_name))
    pdf.set_margins(20, 20, 20)
    pdf.add_page()

    pdf.set_font("Helvetica", "B", 20)
    pdf.cell(0, 10, "Invoice", new_x="LMARGIN", new_y="NEXT")
    pdf.line_text(f"{invoice_number(sale.id)}  ·  Sale reference #{sale.id}".replace("·", "-"))
    pdf.line_text(f"Date of sale: {sold.day} {sold:%b %Y}")
    pdf.ln(6)

    top = pdf.get_y()
    pdf.label("Sold by")
    pdf.line_text(dealer_name, bold=True)
    if dealer_email:
        pdf.line_text(dealer_email)
    left_bottom = pdf.get_y()
    pdf.set_xy(110, top)
    pdf.set_left_margin(110)
    pdf.label("Bill to")
    for i, part in enumerate(_customer(sale)):
        pdf.line_text(part, bold=i == 0)
    pdf.set_left_margin(20)
    pdf.set_xy(20, max(left_bottom, pdf.get_y()) + 8)

    with pdf.table(
        col_widths=(90, 20, 30, 30),
        text_align=("LEFT", "RIGHT", "RIGHT", "RIGHT"),
        line_height=7,
        borders_layout="HORIZONTAL_LINES",
    ) as table:
        pdf.set_font("Helvetica", "B", 9)
        table.row(["Vehicle", "Qty", "Unit price", "Amount"])
        pdf.set_font("Helvetica", "", 10)
        table.row(
            [
                _latin1(sale.vehicle_label),
                str(sale.quantity),
                _money(sale.unit_price),
                _money(sale.total_price),
            ]
        )
    pdf.ln(4)
    pdf.set_font("Helvetica", "B", 12)
    pdf.cell(0, 8, f"Total  {_money(sale.total_price)}", align="R", new_x="LMARGIN", new_y="NEXT")
    pdf.ln(10)
    pdf.set_font("Helvetica", "", 8)
    pdf.set_text_color(110, 110, 110)
    pdf.multi_cell(0, 4.5, NOT_INCLUDED + " Generated by DriveStock from the recorded sale.")
    return bytes(pdf.output())
